type CliSwatchLiteral = readonly [
  weight: string,
  destination: string,
  hex: string,
  outOfSrgb: boolean,
]

const cliGolden = (
  semantic: string,
  destinationSpace: string,
  swatches: readonly CliSwatchLiteral[],
) => ({
  semantic,
  destinationSpace,
  tweenSpace: 'oklch',
  swatches: swatches.map(([weight, destination, hex, outOfSrgb]) => ({
    weight,
    destination,
    hex,
    outOfSrgb,
  })),
})

